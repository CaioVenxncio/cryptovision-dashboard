"""Shared page components of the CryptoVision Design System.

Every dynamic value inserted into HTML goes through `html.escape`; only the
static CSS in `theme.CSS` and these fixed templates are injected as HTML.
"""

from __future__ import annotations

import html
from collections.abc import Sequence

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from cryptovision.ui.theme import CSS, PLOTLY_CONFIG


def apply_styles() -> None:
    st.markdown(CSS, unsafe_allow_html=True)


def _tag(text: str, kind: str = "") -> str:
    css_class = f"cv-tag cv-{html.escape(kind)}" if kind else "cv-tag"
    return f'<span class="{css_class}">{html.escape(text)}</span>'


def page_header(
    eyebrow: str,
    title: str,
    lead: str,
    meta: Sequence[tuple[str, str]] = (),
    tags: Sequence[tuple[str, str]] = (),
) -> None:
    """Eyebrow, title, one-line lead and a monospace metadata row.

    `tags` are (text, kind) with kind in {"", "warn", "live"}; every tag carries
    its meaning in text, never in color alone.
    """
    tag_html = " ".join(_tag(text, kind) for text, kind in tags)
    meta_html = "".join(
        f"<span>{html.escape(label)} <b>{html.escape(value)}</b></span>" for label, value in meta
    )
    st.markdown(
        f'<p class="cv-eyebrow">{html.escape(eyebrow)} {tag_html}</p>'
        f'<h1 class="cv-title">{html.escape(title)}</h1>'
        f'<p class="cv-lead">{html.escape(lead)}</p>'
        + (f'<div class="cv-meta" role="list">{meta_html}</div>' if meta else ""),
        unsafe_allow_html=True,
    )


def section(title: str, description: str = "") -> None:
    """Section heading (a real <h2>) with an optional one-line description."""
    st.markdown(
        f'<div class="cv-section"><h2>{html.escape(title)}</h2>'
        + (f"<p>{html.escape(description)}</p>" if description else "")
        + "</div>",
        unsafe_allow_html=True,
    )


def chart(
    figure: go.Figure,
    *,
    summary: str,
    data: pd.DataFrame | None = None,
    key: str | None = None,
) -> None:
    """A chart with a text summary (screen-reader friendly) and an optional data table."""
    st.plotly_chart(figure, width="stretch", config=PLOTLY_CONFIG, key=key)
    st.caption(summary)
    if data is not None:
        with st.expander("Data table for this chart"):
            st.dataframe(data, width="stretch", placeholder="—")


def sidebar_identity(mode: str) -> None:
    """Compact product identity and data mode at the top of the sidebar."""
    if mode == "demo":
        tag = _tag("Demo · synthetic data", "warn")
        note = "Offline demo. All values are generated, not market data."
    else:
        tag = _tag("Live and local data", "live")
        note = "Live CoinGecko snapshot; historical data and results from local files."
    st.sidebar.markdown(
        f'{tag}<p class="cv-sidenote">{html.escape(note)}</p>', unsafe_allow_html=True
    )


def demo_notice(what: str) -> None:
    st.warning(
        f"**Demo mode — synthetic data.** {what} These values are generated by CryptoVision "
        "and are not market observations.",
        icon=":material/science:",
    )
