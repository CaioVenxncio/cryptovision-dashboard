"""Dataset planning, collection, safe storage, verification and loading.

Directory layout under the data directory (git-ignored):

- `raw/binance_vision/...`: verified Binance archives, reused across runs
- `datasets/<id>/<version>/`: archival datasets (Binance Vision)
- `cache/coingecko/<id>/`: ephemeral CoinGecko caches (expire after 24 hours)
- `synthetic/<id>/<version>/`: synthetic datasets

Each dataset directory holds `data.parquet`, `rejected.parquet` and
`manifest.json`. A dataset is assembled in a hidden staging directory and only
renamed into place after every file, including the manifest, is written, so an
interrupted run never leaves a directory that looks complete.
"""

