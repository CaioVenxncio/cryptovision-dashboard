# CoinGecko API terms §6.1.2 ask that strong encryption be applied to stored Data.
# The cache is not encrypted, so persisting CoinGecko history is disabled until a
# compliant design exists (see docs/data-sources.md). The code path is kept for
# explicit, opt-in use (e.g. tests) and is never reached from the CLI.
COINGECKO_PERSISTENCE_DISABLED = (
    "Storing CoinGecko history is disabled: CoinGecko's API terms (§6.1.2) ask for strong "
    "encryption of stored Data, which this cache does not provide. Use Binance Vision "
    "datasets for historical research. See docs/data-sources.md."
)

SYNTHETIC_ATTRIBUTION = "Synthetic data generated by CryptoVision. Not market observations."
SYNTHETIC_LICENSE_NOTES = "Synthetic data; no third-party rights. MIT, as the project."


def _utc_now() -> datetime:
    return datetime.now(UTC)


@dataclass(frozen=True)
class DatasetPlan:
    """What a collection run would do. Computing a plan never touches the network."""

    config: DatasetConfig
    start: date
    end: date
    output_dir: Path
    requests: tuple[str, ...]
    api_credits: int
    retention: str

    @property
    def estimated_requests(self) -> int:
        return len(self.requests)


def _required[T](value: T | None) -> T:
    """Unwrap a value that DatasetConfig validation guarantees to be present."""
    if value is None:
        raise ValueError("Dataset config is missing a required value.")
    return value


def dataset_dir(config: DatasetConfig, data_dir: Path) -> Path:
    if config.provider == "coingecko":
        return data_dir / "cache" / "coingecko" / config.id
    group = "synthetic" if config.provider == "synthetic" else "datasets"
    return data_dir / group / config.id / config.version


def plan_dataset(
    config: DatasetConfig, data_dir: Path, *, now: datetime | None = None
) -> DatasetPlan:
    now = now or _utc_now()
    output = dataset_dir(config, data_dir)
    if config.provider == "coingecko":
        start, end = coingecko.resolve_period(_required(config.lookback_days), now)
        requests = tuple(
            f"GET {MARKET_CHART_ENDPOINT.format(id=asset.coingecko_id)}"
            f"?vs_currency={config.quote_currency.lower()}&days={config.lookback_days}"
            for asset in config.assets
        )
        return DatasetPlan(config, start, end, output, requests, len(requests), "ephemeral")

    start, end = _required(config.start), _required(config.end)
    requests: tuple[str, ...] = ()
    if config.provider == "binance_vision":
        requests = tuple(
            f"GET {binance.BASE_URL}/{binance.archive_path(asset.pair or '', month)}{suffix}"
            for asset in config.assets
            for month in binance.months_between(start, end)
            for suffix in ("", ".CHECKSUM")
        )
    return DatasetPlan(config, start, end, output, requests, 0, "archival")


@dataclass
class CollectedData:
    frame: pd.DataFrame
    source_files: list[SourceFile] = field(default_factory=list)
    issues: list[Issue] = field(default_factory=list)
    started_at: datetime | None = None
    finished_at: datetime | None = None
    source: dict[str, object] = field(default_factory=dict)
    attribution: str = ""
    license_notes: str = ""


@dataclass(frozen=True)
class CollectionResult:
    path: Path
    manifest: DatasetManifest
    reused: bool


def collect_binance(
    plan: DatasetPlan,
    source: binance.BinanceVisionSource,
    *,
    offline: bool,
    progress: Callable[[str], None] = lambda _: None,
) -> CollectedData:
    config = plan.config
    started = _utc_now()
    frames: list[pd.DataFrame] = []
    files: list[SourceFile] = []
    issues: list[Issue] = []
    for asset in config.assets:
        for month in binance.months_between(plan.start, plan.end):
            pair = asset.pair or ""
            try:
                data, record = source.fetch_archive(pair, month, offline=offline)
            except MissingSourceFileError as exc:
                issues.append(
                    Issue(Severity.ERROR, "missing_source_file", str(exc), asset_id=asset.asset_id)
                )
                continue
            files.append(record)
            frames.append(
                binance.parse_kline_archive(data, asset=asset, quote_currency=config.quote_currency)
            )
            progress(f"{pair} {month}: {'reused' if record.reused_local_copy else 'downloaded'}")
    frame = (
        pd.concat(frames, ignore_index=True)
        if frames
        else normalize_dtypes(
            pd.DataFrame(columns=column_names(DatasetKind.OHLCV)), DatasetKind.OHLCV
        )
    )
    return CollectedData(
        frame=frame,
        source_files=files,
        issues=issues,
        started_at=started,
        finished_at=_utc_now(),
        source={
            "name": "Binance Vision public data",
            "base_url": binance.BASE_URL,
            "path_template": binance.ARCHIVE_TEMPLATE,
            "market": "spot",
            "interval": "1d",
            "price_definition": "Exchange candle prices in the pair's quote asset.",
        },
        attribution=binance.ATTRIBUTION,
        license_notes=binance.LICENSE_NOTES,
    )


def collect_coingecko(
    plan: DatasetPlan,
    client: CoinGeckoClient,
    *,
    progress: Callable[[str], None] = lambda _: None,
) -> CollectedData:
    config = plan.config
    started = _utc_now()
    frames = []
    for asset in config.assets:
        chart = client.get_daily_market_chart(
            _required(asset.coingecko_id),
            days=_required(config.lookback_days),
            vs_currency=config.quote_currency.lower(),
        )
        frames.append(
            coingecko.chart_to_frame(chart, asset=asset, quote_currency=config.quote_currency)
        )
        progress(f"{asset.coingecko_id}: {len(chart.prices)} price points")
    return CollectedData(
        frame=pd.concat(frames, ignore_index=True),
        started_at=started,
        finished_at=_utc_now(),
        source={
            "name": "CoinGecko Demo API",
            "base_url": "https://api.coingecko.com/api/v3",
            "endpoint": MARKET_CHART_ENDPOINT,
            "parameters": {
                "vs_currency": config.quote_currency.lower(),
                "days": config.lookback_days,
            },
            "price_definition": "Aggregated price at 00:00 UTC (automatic daily granularity).",
        },
        attribution=coingecko.ATTRIBUTION,
        license_notes=coingecko.LICENSE_NOTES,
    )


def _write_rejected(rejected: pd.DataFrame, kind: DatasetKind, path: Path) -> None:
    import pyarrow.parquet as pq

    schema = SCHEMAS[kind].append(pa.field("rejection_reason", pa.string()))
    columns = [*column_names(kind), "rejection_reason"]
    frame = normalize_dtypes(rejected.reindex(columns=columns[:-1]), kind)
    frame["rejection_reason"] = rejected["rejection_reason"].astype("object").to_numpy()
    table = pa.Table.from_pandas(frame.loc[:, columns], schema=schema, preserve_index=False)
    buffer = pa.BufferOutputStream()
    pq.write_table(table, buffer, compression="zstd")
    atomic_write_bytes(path, buffer.getvalue().to_pybytes())


def _promote(staging: Path, target: Path, *, replace: bool) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        if not replace:
            raise DatasetExistsError(f"{target} already exists.")
        retired = target.with_name(f".retired-{target.name}-{uuid.uuid4().hex[:8]}")
        target.rename(retired)
        staging.rename(target)
        shutil.rmtree(retired, ignore_errors=True)
    else:
        staging.rename(target)


def store_dataset(
    plan: DatasetPlan,
    collected: CollectedData,
    *,
    config_sha256: str,
    replace: bool,
    now: datetime | None = None,
    allow_unencrypted_coingecko_cache: bool = False,
) -> CollectionResult:
    """Validate collected rows and write the dataset atomically with its manifest."""
    config = plan.config
    if config.provider == "coingecko" and not allow_unencrypted_coingecko_cache:
        raise PersistenceDisabledError(COINGECKO_PERSISTENCE_DISABLED)
    kind = config.kind
    created = now or _utc_now()
    result: ValidationResult = validate_dataset(
        normalize_dtypes(collected.frame, kind),
        kind=kind,
        asset_ids=[asset.asset_id for asset in config.assets],
        start=plan.start,
        end=plan.end,
        rules=config.validation,
    )
    for issue in collected.issues:
        result.report.add(issue)

    target = plan.output_dir
    target.parent.mkdir(parents=True, exist_ok=True)
    staging = target.with_name(f".staging-{target.name}-{uuid.uuid4().hex[:8]}")
    staging.mkdir()
    try:
        write_parquet(result.valid, kind, staging / DATA_FILENAME)
        _write_rejected(result.rejected, kind, staging / REJECTED_FILENAME)
        valid_days = result.valid["timestamp_utc"].dt.date
        manifest = DatasetManifest(
            dataset_id=config.id,
            dataset_version=config.version,
            kind=kind.value,
            provider=config.provider,
            synthetic=config.provider == "synthetic",
            retention="ephemeral" if config.is_ephemeral else "archival",
            expires_at=(
                (collected.finished_at or created) + coingecko.CACHE_RETENTION
                if config.is_ephemeral
                else None
            ),
            status="research_ready" if result.report.research_ready else "failed_validation",
            description=config.description,
            source=collected.source,
            assets=[asset.model_dump(exclude_none=True) for asset in config.assets],
            selection=config.selection.model_dump(mode="json"),
            quote_currency=config.quote_currency,
            frequency=config.frequency,
            requested_period=Period(start=plan.start, end=plan.end),
            actual_period=Period(
                start=valid_days.min() if len(valid_days) else None,
                end=valid_days.max() if len(valid_days) else None,
            ),
            created_at=created,
            retrieval_started_at=collected.started_at,
            retrieval_finished_at=collected.finished_at,
            source_files=collected.source_files,
            config={"sha256": config_sha256, "resolved": config.model_dump(mode="json")},
            files={
                "data": StoredFile(
                    path=DATA_FILENAME,
                    sha256=sha256_file(staging / DATA_FILENAME),
                    rows=len(result.valid),
                ),
                "rejected": StoredFile(
                    path=REJECTED_FILENAME,
                    sha256=sha256_file(staging / REJECTED_FILENAME),
                    rows=len(result.rejected),
                ),
            },
            content_sha256=content_sha256(result.valid, kind),
            validation=result.report.to_dict(),
            software=software_versions(),
            attribution=collected.attribution,
            license_notes=collected.license_notes,
        )
        write_manifest(manifest, staging)
        _promote(staging, target, replace=replace)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return CollectionResult(path=target, manifest=manifest, reused=False)


def existing_result(plan: DatasetPlan, *, force: bool, now: datetime) -> CollectionResult | None:
    """Return a reusable existing dataset, or None if a new one should be built.

    Archival datasets are never overwritten without `force`. A valid, unexpired
    CoinGecko cache is reused instead of spending API credits.
    """
    if not (plan.output_dir / MANIFEST_FILENAME).exists():
        return None
    manifest = read_manifest(plan.output_dir)
    if force:
        return None
    if plan.config.is_ephemeral:
        if manifest.is_expired(now):
            return None
        return CollectionResult(plan.output_dir, manifest, reused=True)
    raise DatasetExistsError(
        f"{plan.output_dir} already exists. Bump the dataset version or use --force."
    )


# --- Verification and loading ---------------------------------------------------------


@dataclass(frozen=True)
class Check:
    name: str
    ok: bool
    detail: str


def verify_dataset(directory: Path, *, data_dir: Path | None = None) -> list[Check]:
    """Recompute every recorded hash and compare it with the manifest."""
    manifest = read_manifest(directory)
    kind = DatasetKind(manifest.kind)
    checks: list[Check] = []
    for name, stored in manifest.files.items():
        path = directory / stored.path
        if not path.exists():
            checks.append(Check(f"file:{name}", False, "missing"))
            continue
        actual = sha256_file(path)
        checks.append(Check(f"file:{name}", actual == stored.sha256, actual))
    data_path = directory / manifest.files["data"].path
    if data_path.exists():
        try:
            frame = read_parquet(data_path, kind)
        except (OSError, ValueError, pa.ArrowException) as exc:
            checks.append(Check("content_sha256", False, f"unreadable ({type(exc).__name__})"))
            return checks
        actual_content = content_sha256(frame, kind)
        checks.append(
            Check("content_sha256", actual_content == manifest.content_sha256, actual_content)
        )
        checks.append(
            Check(
                "row_count",
                len(frame) == manifest.files["data"].rows,
                f"{len(frame)} rows",
            )
        )
    if data_dir is not None:
        for source_file in manifest.source_files:
            path = data_dir / source_file.local_path
            if not path.exists():
                checks.append(Check(f"source:{path.name}", False, "not available locally"))
                continue
            actual = sha256_file(path)
            checks.append(Check(f"source:{path.name}", actual == source_file.sha256, actual))
    return checks


@dataclass(frozen=True)
class LoadedDataset:
    frame: pd.DataFrame
    manifest: DatasetManifest


def load_dataset(
    directory: Path,
    *,
    require_research_ready: bool = True,
    verify: bool = True,
    now: datetime | None = None,
) -> LoadedDataset:
    """Load a stored dataset offline, enforcing expiry, readiness and integrity."""
    manifest = read_manifest(directory)
    if manifest.is_expired(now or _utc_now()):
        raise DatasetExpiredError(
            f"{manifest.dataset_id} expired at {manifest.expires_at}; CoinGecko data may only "
            "be cached for 24 hours. Run purge-expired and collect again."
        )
    if require_research_ready and manifest.status != "research_ready":
        raise DatasetNotReadyError(f"{manifest.dataset_id} failed validation.")
    if verify:
        failed = [check.name for check in verify_dataset(directory) if not check.ok]
        if failed:
            raise DatasetIntegrityError(f"Integrity checks failed: {', '.join(failed)}")
    frame = read_parquet(directory / manifest.files["data"].path, DatasetKind(manifest.kind))
    return LoadedDataset(frame=frame, manifest=manifest)


def purge_expired(data_dir: Path, *, now: datetime | None = None) -> list[Path]:
    """Delete expired ephemeral caches. Returns the removed directories."""
    now = now or _utc_now()
    removed = []
    cache_root = data_dir / "cache"
    for manifest_path in sorted(cache_root.glob("*/*/" + MANIFEST_FILENAME)):
        directory = manifest_path.parent
        if read_manifest(directory).is_expired(now):
            shutil.rmtree(directory)
            removed.append(directory)
    return removed


def list_datasets(data_dir: Path) -> list[tuple[Path, DatasetManifest]]:
    found = []
    for manifest_path in sorted(data_dir.glob("**/" + MANIFEST_FILENAME)):
        if any(part.startswith(".") for part in manifest_path.relative_to(data_dir).parts):
            continue
        found.append((manifest_path.parent, read_manifest(manifest_path.parent)))
    return found
